#!/usr/bin/env python3
"""Create (or refresh) the Lake project skeleton: lean/{lean-toolchain,lakefile.lean,lake-manifest.json,CakeML.lean}
and one stub module per HOL4 theory of every milestone (existing, non-stub files are never touched).
usage: mk_lean_skeleton.py [LEAN_DIR]     (default: <repo>/lean)
The root CakeML.lean imports every milestone module, so `lake build` checks them all."""
import io, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import modules

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(modules.REPO, "lean")
os.makedirs(ROOT, exist_ok=True)


def w(rel, text, force=True):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    if force or not os.path.exists(p):
        io.open(p, "w", encoding="utf-8", newline="\n").write(text)


w("lean-toolchain", "leanprover/lean4:v4.28.0\n")
w("lakefile.lean", '''import Lake
open Lake DSL

package «cakeml» where

-- Pin as in candle-hol4-lean4-study (proving_nohol4/ts/lean): Batteries v4.28.0, rev 495c008c
require batteries from git "https://github.com/leanprover-community/batteries" @ "v4.28.0"

@[default_target]
lean_lib «CakeML» where
''')
w("lake-manifest.json", json.dumps({
    "version": "1.1.0", "packagesDir": ".lake/packages",
    "packages": [{"url": "https://github.com/leanprover-community/batteries", "type": "git", "subDir": None, "scope": "",
                  "rev": "495c008c3e3f4fb4256ff5582ddb3abf3198026f", "name": "batteries", "manifestFile": "lake-manifest.json",
                  "inputRev": "v4.28.0", "inherited": False, "configFile": "lakefile.toml"}],
    "name": "cakeml", "lakeDir": ".lake"}, indent=1) + "\n")
mods = modules.all_modules()
for s, m, mod in mods:
    w(mod.replace(".", "/") + ".lean", f"-- Translation of CakeML `{s}` ({m}). Stub: the translator fills this module.\n", force=False)
w("CakeML.lean", "-- Root: imports every milestone module (generated by workflow/mk_lean_skeleton.py).\n"
  + "".join(f"import {mod}\n" for _, _, mod in mods))
w(".gitignore", ".lake/\nscratch/\n")
print(len(mods), "modules under", ROOT)
